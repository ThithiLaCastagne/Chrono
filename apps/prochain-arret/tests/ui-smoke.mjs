// DOM-only integration tests. This does not claim browser rendering or device QA.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const {Window}=await import(process.env.DOM_TEST_MODULE);
const w=new Window({url:'https://example.test/',settings:{disableJavaScriptFileLoading:true,disableJavaScriptEvaluation:true,disableCSSFileLoading:true}});
w.document.write(readFileSync('dist/index.html','utf8'));
for(const key of ['window','document','localStorage','location'])globalThis[key]=key==='window'?w:w[key];
Object.defineProperty(globalThis,'navigator',{value:w.navigator,configurable:true});
Object.defineProperty(navigator,'onLine',{value:true,configurable:true});
let cleared=false;
Object.defineProperty(navigator,'geolocation',{value:{getCurrentPosition(ok){ok({coords:{latitude:48.87,longitude:2.35,accuracy:10},timestamp:Date.now()})},watchPosition(){return 7},clearWatch(id){cleared=id===7}},configurable:true});
w.HTMLDialogElement.prototype.showModal=function(){this.open=true};
w.HTMLDialogElement.prototype.close=function(){this.open=false};
globalThis.fetch=async()=>({ok:true,json:async()=>({androidAvailable:false})});
// Corrupted storage must not prevent startup.
localStorage.setItem('pa:favorites','{}');localStorage.setItem('pa:recent','null');
await import('../dist/app.js');
const $=s=>document.querySelector(s);
const click=s=>{const e=$(s);assert.ok(e,'Missing '+s);e.click()};
assert.match($('#content').textContent,/Où descendez-vous/);
click('#manual');assert.equal($('#modal').open,true);assert.match($('#modal').textContent,/point de destination/);
$('#pointName').value='Test station';$('#pointLat').value='48,85';$('#pointLon').value='2.35';
$('#manualForm').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
assert.equal($('#modal').open,false);assert.match($('#content').textContent,/Test station/);
assert.equal($('#start').disabled,true);
click('#favorite');assert.equal(JSON.parse(localStorage.getItem('pa:favorites')).length,1);
$('#ack').checked=true;$('#ack').dispatchEvent(new w.Event('change'));
assert.equal($('#start').disabled,false);
click('#start');await new Promise(r=>setTimeout(r,25));
assert.match($('#signal').textContent,/suivi actif/);assert.ok($('#finish'));
click('[data-page="favorites"]');assert.match($('#content').textContent,/Test station/);
click('[data-fav="0"]');assert.ok($('#finish'),'Selecting a new favorite during a journey returns to the active trip');
click('#stop');assert.ok($('#confirmStop'));click('#confirmStop');
assert.equal(cleared,true,'Stop clears the location watcher');assert.match($('#content').textContent,/Où descendez-vous/);
click('[data-page="settings"]');click('[data-pref="sound"]');assert.equal(JSON.parse(localStorage.getItem('pa:prefs')).sound,false);
click('[data-pref="vibration"]');assert.equal(JSON.parse(localStorage.getItem('pa:prefs')).vibration,true,'Cannot disable every alert modality');
click('#helpTop');assert.equal($('#modal').open,true);click('#closeModal');assert.equal($('#modal').open,false);
console.log('DOM flows passed: startup with corrupted storage, manual destination, favorite, permission preflight, start/stop tracking, active-trip protection, settings and help.');
await w.happyDOM.close();
